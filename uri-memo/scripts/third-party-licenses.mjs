// Generates THIRD_PARTY_LICENSES.md (repo root) from the npm and Rust dependencies that ship in
// the app: npm packages that are not dev-only, and every crate reachable from `urinote` through
// normal or build dependencies (all platforms). Identical license texts are printed once.
//
//   npm run licenses
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(APP, "..", "THIRD_PARTY_LICENSES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

/** License-like files in a package folder, sorted by name */
function licenseTexts(dir, explicit) {
  const files = explicit
    ? [explicit]
    : existsSync(dir)
      ? readdirSync(dir).filter((f) => LICENSE_FILE.test(f))
      : [];
  return files
    .sort()
    .map((f) => join(dir, f))
    .filter((p) => existsSync(p))
    .map((p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(APP, "package-lock.json"), "utf8"));
  return Object.entries(lock.packages)
    .filter(([key, p]) => key.startsWith("node_modules/") && !p.dev && !p.devOptional)
    .map(([key, p]) => {
      const dir = join(APP, key);
      const manifest = existsSync(join(dir, "package.json"))
        ? JSON.parse(readFileSync(join(dir, "package.json"), "utf8"))
        : {};
      const license =
        p.license ??
        (typeof manifest.license === "object" ? manifest.license.type : manifest.license);
      return {
        name: key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length),
        version: p.version,
        license: license ?? "UNKNOWN",
        texts: licenseTexts(dir),
        repository:
          "https://www.npmjs.com/package/" + key.slice(key.lastIndexOf("node_modules/") + 13),
      };
    });
}

function rustCrates() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: join(APP, "src-tauri"),
      maxBuffer: 512 * 1024 * 1024,
      encoding: "utf8",
    }),
  );
  const root = meta.resolve.root;
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const reachable = new Set();
  const stack = [root];
  while (stack.length) {
    const node = nodes.get(stack.pop());
    for (const dep of node?.deps ?? []) {
      // dev-dependencies are only used by tests
      if (dep.dep_kinds.every((k) => k.kind === "dev") || reachable.has(dep.pkg)) continue;
      reachable.add(dep.pkg);
      stack.push(dep.pkg);
    }
  }
  return meta.packages
    .filter((p) => reachable.has(p.id))
    .map((p) => {
      const dir = dirname(p.manifest_path);
      return {
        name: p.name,
        version: p.version,
        license: p.license ?? (p.license_file ? "see license file" : "UNKNOWN"),
        texts: licenseTexts(dir, p.license_file ?? undefined),
        repository: p.repository ?? "https://crates.io/crates/${p.name}",
      };
    });
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version);
const npm = npmPackages().sort(byName);
const rust = rustCrates().sort(byName);

// one section per distinct license text
const texts = new Map();
for (const pkg of [...npm, ...rust]) {
  for (const text of pkg.texts) {
    const key = text.replace(/\s+/g, " ");
    if (!texts.has(key)) texts.set(key, { text, users: [] });
    texts.get(key).users.push(`${pkg.name} ${pkg.version}`);
  }
}

const table = (list) =>
  [
    "| Package | Version | License |",
    "|---|---|---|",
    ...list.map((p) => `| ${p.name} | ${p.version} | ${p.license.replace(/\|/g, "\\|")} |`),
  ].join("\n");

const missing = [...npm, ...rust].filter((p) => p.texts.length === 0);
const sections = [...texts.values()]
  .sort((a, b) => b.users.length - a.users.length || a.users[0].localeCompare(b.users[0]))
  .map((t, i) =>
    [
      `### Text ${i + 1}`,
      "",
      `Used by: ${t.users.join(", ")}`,
      "",
      "```text",
      t.text.replace(/```/g, "'''"),
      "```",
    ].join("\n"),
  );

writeFileSync(
  OUT,
  [
    "# Third-party licenses",
    "",
    "Urinote is distributed under the MIT License (see LICENSE). It includes the open-source",
    "software listed below. Generated by `npm run licenses` in `uri-memo/`; do not edit by hand.",
    "",
    `## JavaScript packages (${npm.length})`,
    "",
    table(npm),
    "",
    `## Rust crates (${rust.length})`,
    "",
    table(rust),
    "",
    ...(missing.length
      ? [
          "## Packages without a license file",
          "",
          "These packages declare a license but ship no license text. Where Apache-2.0 is one of the",
          "options, the Apache License 2.0 text below applies. For the others, see the repository.",
          "",
          "| Package | Version | License | Repository |",
          "|---|---|---|---|",
          ...missing.map(
            (p) =>
              `| ${p.name} | ${p.version} | ${p.license.replace(/\|/g, "\\|")} | ${p.repository} |`,
          ),
          "",
        ]
      : []),
    "## License texts",
    "",
    ...sections.flatMap((s) => [s, ""]),
  ].join("\n"),
);
console.log(
  `THIRD_PARTY_LICENSES.md: ${npm.length} npm packages, ${rust.length} crates, ${texts.size} distinct texts, ${missing.length} without a text`,
);
